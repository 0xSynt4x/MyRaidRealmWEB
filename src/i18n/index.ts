function formatMessage(template: string, params?: TranslationParams): string {
  if (!params) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (_, key: string) => {
    const value = params[key];
    return value === undefined || value === null ? '' : String(value);
  });
}

function humanizeMissingKey(key: string): string {
  const lastSegment = key.split('.').filter(Boolean).pop() ?? key;
  return (
    lastSegment
      .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
      .replace(/[_-]+/g, ' ')
      .trim() || key
  );
}

export function isLocale(value: unknown): value is Locale {
  return value === 'zh-CN' || value === 'en';
}

export function setCurrentLocale(locale: Locale) {
  localeState.value = locale;
}

export function getCurrentLocale(): Locale {
  return localeState.value;
}

export function translate(locale: Locale, key: string, params?: TranslationParams): string {
  const template = messages[locale][key] ?? messages[DEFAULT_LOCALE][key] ?? humanizeMissingKey(key);
  return formatMessage(template, params);
}

export function translateEnumDisplay(
  locale: Locale,
  namespace: string,
  value: string | number | null | undefined,
  fallback?: string,
): string {
  if (value === null || value === undefined || value === '') {
    return fallback ?? '';
  }

  const normalizedValue = String(value);

  return (
    enumDisplayMessages[locale]?.[namespace]?.[normalizedValue] ??
    enumDisplayMessages[DEFAULT_LOCALE]?.[namespace]?.[normalizedValue] ??
    fallback ??
    normalizedValue
  );
}

function getFieldTranslationMeta(locale: Locale, fieldPath: string): FieldTranslationMeta {
  return {
    ...fieldMessages[DEFAULT_LOCALE]?.[fieldPath],
    ...fieldMessages[locale]?.[fieldPath],
  };
}

export function translateField(locale: Locale, fieldPath: string, kind: FieldTranslationKind, fallback = ''): string {
  return getFieldTranslationMeta(locale, fieldPath)[kind] ?? fallback;
}

export function getFieldTranslation(
  locale: Locale,
  fieldPath: string,
  fallback: FieldTranslationMeta = {},
): Required<FieldTranslationMeta> {
  const meta = getFieldTranslationMeta(locale, fieldPath);
  return {
    label: meta.label ?? fallback.label ?? '',
    placeholder: meta.placeholder ?? fallback.placeholder ?? '',
    help: meta.help ?? fallback.help ?? '',
  };
}

export function tCurrent(key: string, params?: TranslationParams): string {
  return translate(localeState.value, key, params);
}

export function enumDisplayCurrent(
  namespace: string,
  value: string | number | null | undefined,
  fallback?: string,
): string {
  return translateEnumDisplay(localeState.value, namespace, value, fallback);
}

export function fieldTextCurrent(fieldPath: string, kind: FieldTranslationKind, fallback = ''): string {
  return translateField(localeState.value, fieldPath, kind, fallback);
}

export function fieldMetaCurrent(
  fieldPath: string,
  fallback: FieldTranslationMeta = {},
): Required<FieldTranslationMeta> {
  return getFieldTranslation(localeState.value, fieldPath, fallback);
}

export function syncDocumentLocale(locale: Locale) {
  setCurrentLocale(locale);
  document.documentElement.lang = locale;
  // 浏览器标签页标题跟着界面语言走。
  // 模板 index.html 里那条静态 title 只作 JS 执行前的兜底（不然会先闪一下网址），
  // 切语言后必须再刷一次，否则标签页还停在切换前的那个名字。
  document.title = translate(locale, 'setup.home.gameTitle');
}

export function useI18n() {
  return {
    locale: computed(() => localeState.value),
    t: tCurrent,
    enumDisplay: enumDisplayCurrent,
    fieldText: fieldTextCurrent,
    fieldMeta: fieldMetaCurrent,
  };
}
